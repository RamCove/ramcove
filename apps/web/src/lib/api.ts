/** API access. The browser always talks to the Next proxy at /api/*, which forwards the session cookie. */

import type { components } from "./api-types";

export const API_ORIGIN = process.env.ROOM_API_ORIGIN ?? "http://127.0.0.1:8787";

export type ApiError = { code: string; message: string; reference?: string };

export class ApiFailure extends Error {
  constructor(
    public status: number,
    public error: ApiError,
  ) {
    super(error.message);
  }
}

/** Browser fetch through the proxy. */
export async function clientFetch<T>(
  path: string,
  init?: RequestInit & { idempotencyKey?: string },
): Promise<T> {
  const headers = new Headers(init?.headers);
  if (init?.idempotencyKey) headers.set("idempotency-key", init.idempotencyKey);
  if (init?.body && !(init.body instanceof FormData)) headers.set("content-type", "application/json");
  const res = await fetch(`/api${path}`, { ...init, headers, credentials: "same-origin" });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) {
    throw new ApiFailure(res.status, body.error ?? { code: "unreachable", message: "Request failed" });
  }
  return body as T;
}

/**
 * Request bodies checked against the server's own OpenAPI document.
 *
 * `api-types.ts` is generated by `make openapi` from the running API. Posting through this helper
 * means a field renamed on the server breaks `npm run typecheck` instead of failing silently in the
 * browser. Responses are not typed this way: the API returns plain documents and does not declare
 * response schemas yet, so pages still describe the shapes they read.
 */
export type RequestBody<K extends keyof components["schemas"]> = components["schemas"][K];

export function postJson<K extends keyof components["schemas"], T = unknown>(
  path: string,
  body: RequestBody<K>,
  init?: { idempotencyKey?: string },
): Promise<T> {
  return clientFetch<T>(path, { method: "POST", body: JSON.stringify(body), ...init });
}
